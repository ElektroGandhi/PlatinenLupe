"""Generate lettering.scad: letters as ready-made polygons (matplotlib, DejaVu Sans Bold).

Why: OpenSCAD 2021.01 (the Flatpak build) renders nothing with text() on some systems --
"Current top level object is empty", no error, no warning (seen 2026-10-27, also with
`use <...ttf>` and OPENSCAD_FONT_PATH). Plain polygons work in every OpenSCAD version.

  python lettering.py   -> writes lettering.scad next to this file
"""

from pathlib import Path

from matplotlib.font_manager import FontProperties
from matplotlib.textpath import TextPath

FONT = FontProperties(family="DejaVu Sans", weight="bold")
# module name -> (text, cap height in mm). Polygons are centred on the origin (0, 0).
LETTERING = {
    "lettering_name": ("PLATINENLUPE", 5.0),
    "lettering_a": ("A", 3.5),
    "lettering_b": ("B", 3.5),
    "lettering_run": ("RUN", 3.0),       # USB selector, engraved on the plinth
    "lettering_flash": ("FLASH", 3.0),
}


def polygon_scad(text: str, cap_height: float) -> str:
    path = TextPath((0, 0), text, size=1, prop=FONT)
    polys = [p for p in path.to_polygons() if len(p) >= 3]
    cap = TextPath((0, 0), "H", size=1, prop=FONT).get_extents().height
    s = cap_height / cap
    xs = [x for p in polys for x, _ in p]
    ys = [y for p in polys for _, y in p]
    mx, my = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    points, paths, n = [], [], 0
    for p in polys:
        paths.append(list(range(n, n + len(p))))
        points += [f"[{(x - mx) * s:.3f},{(y - my) * s:.3f}]" for x, y in p]
        n += len(p)
    # OpenSCAD evaluates multiple paths even-odd: inner holes (O, A, P ...) stay holes
    return f"polygon(points=[{','.join(points)}], paths={paths});"


def main() -> None:
    out = ["// GENERATED by lettering.py -- do not edit by hand.\n"]
    for module, (text, height) in LETTERING.items():
        out.append(f'// "{text}", cap height {height} mm, centred on the origin\n'
                   f"module {module}() {{ {polygon_scad(text, height)} }}\n")
    target = Path(__file__).with_name("lettering.scad")
    target.write_text("\n".join(out), encoding="utf-8")
    print(target.name, target.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
