# PlatformIO pre-script: packs ../web/index.html (gzip) into src/home_side/page.h.
# One page for every mode — the device serves the very same file the server serves.
# page.h is generated and not part of the repository.
import gzip
from pathlib import Path

try:
    Import("env")  # noqa: F821 — only defined inside PlatformIO
    root = Path(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    root = Path(__file__).resolve().parents[1]

source = root.parent / "web" / "index.html"
target = root / "src" / "home_side" / "page.h"
data = gzip.compress(source.read_bytes(), compresslevel=9, mtime=0)
body = ",".join(str(b) for b in data)
text = (
    "// GENERATED by scripts/embed_page.py from web/index.html — do not edit\n"
    "#pragma once\n#include <Arduino.h>\n"
    f"static const uint8_t PAGE_GZ[] PROGMEM = {{{body}}};\n"
    f"static const size_t PAGE_GZ_LEN = {len(data)};\n"
)
if not target.exists() or target.read_text() != text:
    target.write_text(text)
print(f"page.h: {source.stat().st_size} -> {len(data)} bytes gzip")
